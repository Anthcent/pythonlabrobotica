total = 0  # Asigna o actualiza un valor.
for numero in range(1, 6):  # Repite el bloque para cada elemento del recorrido.
    total += numero  # Equivale a total = total + numero.
    print("Acumulado:", total)  # Muestra el resultado en la consola.
print("Suma total:", total)  # Muestra el resultado en la consola.
