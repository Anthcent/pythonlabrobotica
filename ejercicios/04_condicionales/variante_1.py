# Los bloques de if y else llevan sangría de 4 espacios.
edad = 19  # Asigna o actualiza un valor.
if edad >= 18:  # Comprueba la condición; ejecuta el bloque si es verdadera.
    print("Eres mayor de edad")  # Muestra el resultado en la consola.
else:  # Alternativa cuando no se cumple la condición anterior.
    print("Eres menor de edad")  # Muestra el resultado en la consola.
